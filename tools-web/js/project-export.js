    function updateCodeOutput() {
      const rgbBg = getRgb565Hex(APP_STATE.bgColor);
      const holdFrames = Math.round(APP_STATE.holdDurationMs / 40);

      const gaugeLayer = APP_STATE.layers.find(l => l.type === 'gauge' || l.type === 'ring');
      const rgbGauge = gaugeLayer ? getRgb565Hex(gaugeLayer.color) : '0x38bdf8';
      const gaugeRadius = gaugeLayer ? (gaugeLayer.radius || 100) : 100;
      const gaugeSegments = gaugeLayer ? (gaugeLayer.segments || 40) : 40;

      const spriteLayer = APP_STATE.layers.find(l => l.type === 'sprite');
      let spriteDataCode = '// No custom sprite layer in composition\n';

      if (spriteLayer && spriteLayer.pixels && spriteLayer.w && spriteLayer.h) {
        const total = spriteLayer.w * spriteLayer.h;
        spriteDataCode = `/* Sprite Asset: ${spriteLayer.w}x${spriteLayer.h} px (RGB565) */\n`;
        spriteDataCode += `#define CONFIG_BOOT_SPRITE_WIDTH   ${spriteLayer.w}\n`;
        spriteDataCode += `#define CONFIG_BOOT_SPRITE_HEIGHT  ${spriteLayer.h}\n`;
        spriteDataCode += `#define CONFIG_BOOT_SPRITE_SCALE   ${spriteLayer.scale || 2}\n`;
        spriteDataCode += `#define CONFIG_BOOT_SPRITE_OFFSET_X ${spriteLayer.offsetX || 0}\n`;
        spriteDataCode += `#define CONFIG_BOOT_SPRITE_OFFSET_Y ${spriteLayer.offsetY || 0}\n`;
        spriteDataCode += `static const uint16_t s_boot_custom_sprite[${total}] = {\n`;

        for (let y = 0; y < spriteLayer.h; y++) {
          let rowStr = '    ';
          for (let x = 0; x < spriteLayer.w; x++) {
            const col = spriteLayer.pixels[y * spriteLayer.w + x];
            rowStr += (col ? getRgb565Hex(col) : '0x0000') + ', ';
          }
          spriteDataCode += rowStr + '\n';
        }
        spriteDataCode += '};\n';
      }

      let code = `/**
 * @file boot_logo_custom.h
 * @brief Auto-generated by ESP-IDF Boot Display Studio & Universal Composer
 * Target: ESP32-P4 / GC9A01 Autonomous LP-Core & HP DMA Driver
 */

#pragma once

#include <stdint.h>
#include "boot_display_types.h"

/* Kconfig Hardware Defaults matching current Studio Composition */
#define CONFIG_BOOT_DISPLAY_COLOR_BG               ${rgbBg}
#define CONFIG_BOOT_DISPLAY_COLOR_GAUGE            ${rgbGauge}
#define CONFIG_BOOT_DISPLAY_RING_SEGMENTS          ${gaugeSegments}
#define CONFIG_BOOT_DISPLAY_RING_RADIUS            ${gaugeRadius}
#define CONFIG_BOOT_DISPLAY_CELEBRATION_THRESHOLD  ${APP_STATE.thresholdPercent}
#define CONFIG_BOOT_DISPLAY_COMPLETION_HOLD_FRAMES ${holdFrames}
#define CONFIG_BOOT_DISPLAY_DEFAULT_MODE           ${APP_STATE.bootMode}

${spriteDataCode}
/* Hardware Initializer Template */
static const boot_display_config_t s_boot_custom_config = {
    .mosi_pin = GPIO_NUM_2,
    .sclk_pin = GPIO_NUM_3,
    .cs_pin   = GPIO_NUM_4,
    .dc_pin   = GPIO_NUM_5,
    .rst_pin  = GPIO_NUM_49,
    .spi_clock_hz = 8000000,
    .mode = (boot_display_mode_t)${APP_STATE.bootMode},
    .backend = BOOT_DISPLAY_BACKEND_${APP_STATE.engine === 'hp' ? 'HP_SPI' : 'LP_SPI'},
    .geometry = {
        .width = 240,
        .height = 240,
        .is_circular = true
    },
    .colors = {
        .bg_color = ${rgbBg},
        .ring_color = ${rgbGauge},
        .body_color = 0xFFFF,
        .accent_color = 0x38bdf8
    }
};
`;
      document.getElementById('codeOutput').value = code;
    }

    function copyHeaderCode() {
      const code = document.getElementById('codeOutput').value;
      navigator.clipboard.writeText(code).then(() => {
        logTerminal('[EXP] C-Header code copied to clipboard.', 'info');
      });
    }

    function downloadHeaderFile() {
      const code = document.getElementById('codeOutput').value;
      const blob = new Blob([code], { type: 'text/x-csrc' });
      const a = document.createElement('a');
      a.href = URL.createObjectURL(blob);
      a.download = 'boot_logo_custom.h';
      a.click();
      logTerminal('[EXP] Downloaded boot_logo_custom.h.', 'info');
    }

    function saveProjectJson() {
      const payload = {
        project: 'ESP32 Boot Display Composition',
        version: '2.5.0',
        timestamp: new Date().toISOString(),
        engine: APP_STATE.engine,
        bootMode: APP_STATE.bootMode,
        thresholdPercent: APP_STATE.thresholdPercent,
        holdDurationMs: APP_STATE.holdDurationMs,
        bgColor: APP_STATE.bgColor,
        layers: APP_STATE.layers
      };

      const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
      const a = document.createElement('a');
      a.href = URL.createObjectURL(blob);
      a.download = 'boot_display_project.bootproj';
      a.click();
      logTerminal('[EXP] Saved project to boot_display_project.bootproj', 'info');
    }

    function onProjectFileSelected(evt) {
      const file = evt.target.files[0];
      if (!file) return;

      const reader = new FileReader();
      reader.onload = (e) => {
        try {
          const data = JSON.parse(e.target.result);
          if (data.layers && Array.isArray(data.layers)) {
            APP_STATE.layers = data.layers;
            APP_STATE.selectedLayerId = data.layers[0] ? data.layers[0].id : null;
            if (data.bgColor) {
              APP_STATE.bgColor = data.bgColor;
              document.getElementById('pickBgColor').value = data.bgColor;
              document.getElementById('hexBgColor').textContent = `${data.bgColor} (RGB565: ${getRgb565Hex(data.bgColor)})`;
            }
            if (data.engine) setEngine(data.engine);
            if (data.bootMode !== undefined) {
              APP_STATE.bootMode = data.bootMode;
              document.getElementById('selBootMode').value = data.bootMode;
            }
            renderLayerList();
            renderLayerInspector();
            updateCodeOutput();
            logTerminal(`[LOAD] Successfully loaded project "${file.name}" with ${data.layers.length} layers.`, 'info');
          } else {
            logTerminal('[ERR] Invalid project file format.', 'err');
          }
        } catch (err) {
          logTerminal('[ERR] Failed to parse project file: ' + err.message, 'err');
        }
      };
      reader.readAsText(file);
      evt.target.value = '';
    }

